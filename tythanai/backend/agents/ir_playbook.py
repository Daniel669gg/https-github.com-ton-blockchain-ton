class IRPlaybookGenerator:
    def __init__(self, output_dir: Optional[str] = None) -> None:
        if output_dir:
            self._reports_dir = Path(output_dir)
        else:
            self._reports_dir = Path("reports/ir_playbooks")
        self._reports_dir.mkdir(parents=True, exist_ok=True)

    def generate(
        self,
        finding: Finding,
        risk_score: float = 75.0,
        scan_id: Optional[str] = None,
    ) -> Optional["IRPlaybook"]:
        if finding.severity not in ("CRITICAL", "HIGH") and risk_score <= 60:
            return None

        vuln_type = _detect_vuln_type(finding.rule_id, finding.cwe_id)
        template_steps = _PLAYBOOK_TEMPLATES.get(vuln_type, _PLAYBOOK_TEMPLATES["default"])

        steps: List[PlaybookStep] = []
        for idx, tpl in enumerate(template_steps, 1):
            # Fill in finding-specific details in action/rationale where applicable
            action = tpl["action"]
            rationale = tpl["rationale"]
            commands = list(tpl["commands"])

            # Inject file context into first immediate step
            if idx == 1 and tpl["phase"] == "immediate":
                commands.append(f"# Affected file: {finding.file} (line {finding.line})")

            steps.append(
                PlaybookStep(
                    step_number=idx,
                    phase=tpl["phase"],
                    action=action,
                    rationale=rationale,
                    commands=commands,
                    owner=tpl["owner"],
                    time_limit=tpl["time_limit"],
                )
            )

        blockchain_steps: List[str] = (
            _BLOCKCHAIN_STEPS if _is_blockchain_vuln(finding.rule_id) else []
        )

        attck_ids = _ATTCK_MAPPING.get(vuln_type, _ATTCK_MAPPING["default"])
        effective_scan_id = scan_id or str(uuid.uuid4())

        return IRPlaybook(
            playbook_id=str(uuid.uuid4()),
            scan_id=effective_scan_id,
            vulnerability_type=vuln_type,
            severity=finding.severity,
            risk_score=risk_score,
            attck_ids=attck_ids,
            cwe_id=finding.cwe_id or "CWE-0",
            affected_file=finding.file,
            created_at=datetime.now(timezone.utc).isoformat(),
            steps=steps,
            blockchain_steps=blockchain_steps,
        )

    def save(self, playbook: IRPlaybook) -> Path:
        safe_scan_id = playbook.scan_id.replace("/", "_").replace("\\", "_")
        path = self._reports_dir / f"{safe_scan_id}.md"
        path.write_text(playbook.to_markdown(), encoding="utf-8")
        logger.info("IR playbook saved to %s", path)
        return path

    def generate_and_save(
        self,
        finding: Finding,
        risk_score: float = 75.0,
        scan_id: Optional[str] = None,
    ) -> Optional[Path]:
        try:
            playbook = self.generate(finding, risk_score=risk_score, scan_id=scan_id)
            return self.save(playbook)
        except ValueError as exc:
            logger.debug("Playbook not generated: %s", exc)
            return None
        except Exception as exc:
            logger.error("Failed to generate/save IR playbook: %s", exc, exc_info=True)
            return None


# ---------------------------------------------------------------------------
# Module-level convenience function
# ---------------------------------------------------------------------------


def generate_ir_playbook(finding: Finding, risk_score: float = 75.0) -> IRPlaybook:
    """Generate an IR playbook for a critical finding.

    Raises ValueError if the finding does not meet the severity/risk threshold.
    """
    return IRPlaybookGenerator().generate(finding, risk_score=risk_score)
