class PlaybookStep(BaseModel):
    step_number: int
    phase: str  # "immediate"|"containment"|"eradication"|"recovery"|"verification"|"lessons_learned"
    action: str
    rationale: str
    commands: List[str]  # concrete shell/code commands where applicable
    owner: str  # "security-team"|"dev-team"|"ops-team"|"management"
    time_limit: str  # e.g. "30 minutes", "2 hours", "48 hours"


class IRPlaybook(BaseModel):
    playbook_id: str
    scan_id: str
    vulnerability_type: str
    severity: str
    risk_score: float
    attck_ids: List[str]
    cwe_id: str
    affected_file: str
    created_at: str
    steps: List[PlaybookStep]
    blockchain_steps: List[str]  # empty unless blockchain vuln detected

    def to_markdown(self) -> str:
        lines: List[str] = []
        lines.append(f"# Incident Response Playbook: {self.vulnerability_type.replace('_', ' ').title()}")
        lines.append("")
        lines.append("## Metadata")
        lines.append("")
        lines.append(f"| Field | Value |")
        lines.append(f"|-------|-------|")
        lines.append(f"| Playbook ID | `{self.playbook_id}` |")
        lines.append(f"| Scan ID | `{self.scan_id}` |")
        lines.append(f"| Vulnerability Type | {self.vulnerability_type} |")
        lines.append(f"| Severity | **{self.severity}** |")
        lines.append(f"| Risk Score | {self.risk_score:.1f} / 100 |")
        lines.append(f"| CWE ID | {self.cwe_id} |")
        lines.append(f"| Affected File | `{self.affected_file}` |")
        lines.append(f"| Created At | {self.created_at} |")
        if self.attck_ids:
            lines.append(f"| ATT&CK IDs | {', '.join(self.attck_ids)} |")
        lines.append("")

        if self.blockchain_steps:
            lines.append("## Blockchain-Specific Emergency Actions")
            lines.append("")
            lines.append("> **WARNING**: Smart contract vulnerability detected. Execute these steps IMMEDIATELY before standard IR.")
            lines.append("")
            for i, step in enumerate(self.blockchain_steps, 1):
                lines.append(f"{i}. {step}")
            lines.append("")

        lines.append("## Response Steps")
        lines.append("")

        phases_seen: List[str] = []
        for step in self.steps:
            if step.phase not in phases_seen:
                phases_seen.append(step.phase)
                lines.append(f"### Phase: {step.phase.replace('_', ' ').title()}")
                lines.append("")

            lines.append(f"#### Step {step.step_number}: {step.action}")
            lines.append("")
            lines.append(f"- **Owner**: {step.owner}")
            lines.append(f"- **Time Limit**: {step.time_limit}")
            lines.append(f"- **Rationale**: {step.rationale}")
            if step.commands:
                lines.append("")
                lines.append("```bash")
                for cmd in step.commands:
                    lines.append(cmd)
                lines.append("```")
            lines.append("")

        lines.append("---")
        lines.append(f"*Generated by TythanAI IR Playbook Generator at {self.created_at}*")
        return "\n".join(lines)


