def _detect_vuln_type(rule_id: str, cwe_id: str) -> str:
    combined = (rule_id + " " + cwe_id).lower()
    for vuln_type, keywords in _VULN_TYPE_KEYWORDS.items():
        if any(kw.lower() in combined for kw in keywords):
            return vuln_type
    return "default"


def _is_blockchain_vuln(rule_id: str) -> bool:
    return any(kw in rule_id.lower() for kw in _BLOCKCHAIN_KEYWORDS)


